class Especificacoes:
    def __init__(
        self,
        motor,
        potencia,
        torque,
        cambio,
        tracao,
        aceleracao,
        velocidade_maxima
    ):
        self.motor = motor
        self.potencia = potencia
        self.torque = torque
        self.cambio = cambio
        self.tracao = tracao
        self.aceleracao = aceleracao
        self.velocidade_maxima = velocidade_maxima